// ===== TSCONFIG.JSON EXPLAINED =====
console.log("=== tsconfig.json Configuration ===");

interface TSConfig {
    compilerOptions: {
        target: string;        // What JS version to compile to
        module: string;        // Module system (commonjs, es6, etc.)
        outDir: string;        // Where to put compiled JS files
        rootDir: string;       // Where TypeScript source files are
        strict: boolean;       // Enable all strict type checking
        esModuleInterop: boolean;     // Better import/export compatibility
        skipLibCheck: boolean;        // Skip type checking of .d.ts files
        forceConsistentCasingInFileNames: boolean;
    };
    include: string[];         // Which files to compile
    exclude: string[];         // Which files to ignore
}

const exampleTSConfig: TSConfig = {
    compilerOptions: {
        target: "ES2020",
        module: "commonjs",
        outDir: "./dist",          // 📁 Where compiled JS goes
        rootDir: "./src",          // 📁 Where TS source files are
        strict: true,              // Enable strict type checking
        esModuleInterop: true,
        skipLibCheck: true,
        forceConsistentCasingInFileNames: true
    },
    include: ["src/**/*"],         // Which files to compile
    exclude: ["node_modules", "dist"]   // Which files to ignore
};

console.log("Example tsconfig.json:", JSON.stringify(exampleTSConfig, null, 2));

