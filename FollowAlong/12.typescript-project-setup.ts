// ===== WATCH MODE EXPLAINED =====
console.log("=== Watch Mode ===");
/*
Watch Mode (tsc --watch):
- Monitors your .ts files for changes
- Automatically recompiles when you save
- Keeps running until you stop it (Ctrl+C)
- Shows compilation errors in real-time

Example workflow:
1. Terminal 1: npx tsc --watch    ← Keeps TypeScript compiler running
2. Terminal 2: lite-server        ← Serves your files
3. Edit .ts files → Auto-compiles → Browser auto-refreshes
*/

// ===== LITE-SERVER CONCEPT =====
console.log("=== lite-server Development Server ===");
/*
lite-server:
- Lightweight development web server
- Serves static files (HTML, CSS, JS)
- Auto-refreshes browser when files change
- Perfect for frontend development

Installation:
npm install lite-server --save-dev

Usage:
npx lite-server

What it does:
1. Serves files from current directory
2. Opens browser automatically
3. Watches for file changes
4. Refreshes browser when JS/HTML changes

Perfect combo with tsc --watch:
- Terminal 1: npx tsc --watch     ← Compiles TS → JS
- Terminal 2: npx lite-server     ← Serves files + auto-refresh
*/

