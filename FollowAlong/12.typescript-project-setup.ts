// ===== TYPESCRIPT PROJECT SETUP & COMPILATION =====
// Understanding how TypeScript works in real projects

console.log("=== TypeScript Compilation Process ===");
/*
TypeScript is a SUPERSET of JavaScript that adds static typing.
It needs to be COMPILED (transpiled) to JavaScript to run in browsers/Node.js.

FLOW: .ts files → TypeScript Compiler (tsc) → .js files → Browser/Node.js

Example:
- You write: function greet(name: string): string { return Hello ${name}; }
- Compiler outputs: function greet(name) { return "Hello " + name; }
*/

console.log("=== Project Structure ===");
/*
my-project/
├── src/                    ← SOURCE directory (your TypeScript code)
│   ├── index.ts           ← Main TypeScript entry point
│   ├── utils/
│   │   └── helpers.ts
│   └── components/
│       └── Button.ts
├── dist/                   ← DISTRIBUTION directory (compiled JavaScript)
│   ├── index.js           ← Compiled from src/index.ts
│   ├── utils/
│   │   └── helpers.js
│   └── components/
│       └── Button.js
├── public/                 ← Static files (HTML, CSS, images)
│   └── index.html         ← HTML file that loads the compiled JS
├── tsconfig.json          ← TypeScript configuration
├── package.json           ← Project metadata & dependencies
├── package-lock.json      ← Exact dependency versions (auto-generated)
└── node_modules/          ← Installed dependencies (don't commit this!)
*/

// ===== DIRECTORY EXPLANATIONS =====

console.log("=== SRC Directory ===");
/*
src/ - Where you write your TypeScript code
- Contains ALL your .ts files
- This is your "development" code
- Has type annotations, interfaces, etc.
- NOT what runs in the browser
- Example: src/index.ts, src/components/Button.ts
*/

console.log("=== DIST Directory ===");
/*
dist/ - Where compiled JavaScript goes
- Generated automatically by TypeScript compiler
- Contains .js files (no types)
- This is what actually runs in browser/Node.js
- Should be in .gitignore (don't commit compiled files)
- Example: dist/index.js, dist/components/Button.js
*/

